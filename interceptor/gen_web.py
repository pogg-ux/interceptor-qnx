"""Embed web/ files into web_files.h so the Interceptor serves them with no extra files on QNX."""
import os
here = os.path.dirname(os.path.abspath(__file__))
files = [("index.html", "text/html"), ("manifest.json", "application/manifest+json"),
         ("sw.js", "text/javascript"), ("icon.svg", "image/svg+xml")]
out = ["/* Generated by gen_web.py from web/. Do not edit. */", "#ifndef WEB_FILES_H", "#define WEB_FILES_H", ""]
for name, ctype in files:
    data = open(os.path.join(here, "web", name), "rb").read()
    ident = "WEB_" + name.replace(".", "_").upper()
    out.append("static const unsigned char %s[] = {" % ident)
    for i in range(0, len(data), 20):
        out.append("  " + ",".join(str(b) for b in data[i:i + 20]) + ",")
    out.append("};")
out.append("static const struct { const char *path, *type; const unsigned char *data; unsigned long len; } WEB_FILES[] = {")
for name, ctype in files:
    ident = "WEB_" + name.replace(".", "_").upper()
    path = "/" if name == "index.html" else "/" + name
    out.append('  { "%s", "%s", %s, sizeof %s },' % (path, ctype, ident, ident))
out.append("};")
out.append("#endif")
open(os.path.join(here, "web_files.h"), "w").write("\n".join(out) + "\n")
print("web_files.h written")
